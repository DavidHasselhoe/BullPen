/**
 * Turns the reviewed Academy staging files into one migration.
 *
 *   npx tsx scripts/academy-apply-staging.ts
 *
 * Reads content/academy-staging/{interleave-checks,demos}.json and the live
 * lessons, builds each course's new sequence (a check right after its read, a
 * demo right before the course's closing scenario), and writes
 * supabase/migrations/169_academy_interleave.sql plus
 * content/academy-staging/sequences.json (the before/after per course, for
 * review). It applies nothing: the migration goes through the Supabase MCP like
 * every other one, after the content has been read and approved.
 */

import { config } from 'dotenv';
config({ path: '.env.local' });

import fs from 'node:fs';
import path from 'node:path';
import { createServerClient } from '../lib/supabase/client';
import { DemoContentSchema, QuizContentSchema } from '../types/academy';

const STAGING = path.join('content', 'academy-staging');
const MIGRATION = path.join('supabase', 'migrations', '169_academy_interleave.sql');

interface Staged { courseSlug: string; slug: string; title: string; xpReward: number; content: unknown }
interface Check extends Staged { afterLessonSlug: string }
interface Demo extends Staged { beforeLessonSlug: string }
interface Live { slug: string; title: string; type: string; order_index: number; academy_courses: { slug: string } }
type Item = { slug: string; title: string; type: string; isNew: boolean; staged?: Staged };

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sqlJson = (v: unknown) => {
  const json = JSON.stringify(v);
  if (json.includes('$json$')) throw new Error('content contains the dollar-quote tag');
  return `$json$${json}$json$::jsonb`;
};

async function main() {
  const checks: Check[] = JSON.parse(fs.readFileSync(path.join(STAGING, 'interleave-checks.json'), 'utf8'));
  const demos: Demo[] = JSON.parse(fs.readFileSync(path.join(STAGING, 'demos.json'), 'utf8'));
  for (const c of checks) QuizContentSchema.parse(c.content);
  for (const d of demos) DemoContentSchema.parse(d.content);

  const { data, error } = await createServerClient()
    .from('academy_lessons')
    .select('slug, title, type, order_index, academy_courses!inner(slug)')
    .order('order_index');
  if (error) throw error;

  const live = new Map<string, Item[]>();
  for (const l of (data ?? []) as unknown as Live[]) {
    const list = live.get(l.academy_courses.slug) ?? [];
    list.push({ slug: l.slug, title: l.title, type: l.type, isNew: false });
    live.set(l.academy_courses.slug, list);
  }

  const touched = new Set([...checks, ...demos].map((s) => s.courseSlug));
  const sequences: Record<string, { before: string[]; after: string[] }> = {};
  const sql: string[] = [
    '-- Academy: no two read lessons in a row, and a hands-on demo where a real',
    '-- BullPen screen fits. Generated by scripts/academy-apply-staging.ts from',
    '-- content/academy-staging/ after review. Checks are drafted from the read',
    "-- lesson they follow (scripts/academy-interleave-checks.ts); demos are",
    '-- hand-written tours over targets that exist on each surface.',
    '',
  ];

  for (const course of [...touched].sort()) {
    const before = live.get(course);
    if (!before) throw new Error(`Unknown course ${course}`);
    const after: Item[] = [];
    for (const item of before) {
      const demo = demos.find((d) => d.courseSlug === course && d.beforeLessonSlug === item.slug);
      if (demo) after.push({ slug: demo.slug, title: demo.title, type: 'demo', isNew: true, staged: demo });
      after.push(item);
      const check = checks.find((c) => c.courseSlug === course && c.afterLessonSlug === item.slug);
      if (check) after.push({ slug: check.slug, title: check.title, type: 'quiz', isNew: true, staged: check });
    }
    const missing = [...checks, ...demos].filter((s) => s.courseSlug === course && !after.some((a) => a.slug === s.slug));
    if (missing.length) throw new Error(`${course}: anchor lesson not found for ${missing.map((m) => m.slug).join(', ')}`);

    sequences[course] = {
      before: before.map((i) => `${i.type}: ${i.title}`),
      after: after.map((i) => `${i.isNew ? '+ ' : ''}${i.type}: ${i.title}`),
    };

    sql.push(`-- ${course}`);
    after.forEach((item, ord) => {
      if (item.isNew && item.staged) {
        sql.push(
          `INSERT INTO academy_lessons (course_id, slug, title, type, order_index, xp_reward, content)\n` +
            `SELECT id, ${sqlString(item.slug)}, ${sqlString(item.title)}, ${sqlString(item.type)}, ${ord}, ${item.staged.xpReward}, ${sqlJson(item.staged.content)}\n` +
            `FROM academy_courses WHERE slug = ${sqlString(course)}\nON CONFLICT (course_id, slug) DO NOTHING;`,
        );
      }
    });
    const values = after.filter((i) => !i.isNew).map((i) => `(${sqlString(i.slug)}, ${after.indexOf(i)})`).join(', ');
    sql.push(
      `UPDATE academy_lessons l SET order_index = v.ord FROM (VALUES ${values}) AS v(slug, ord), academy_courses c\n` +
        `WHERE c.slug = ${sqlString(course)} AND l.course_id = c.id AND l.slug = v.slug;`,
      '',
    );
  }

  // Options basics: "a bet that the price goes up" is wrong from the seller's
  // side and frames options as gambling; "worth cashing in for a profit"
  // ignores the premium. Content error found in the 2026-10-13 review.
  sql.push(
    "-- options-basics: correct the Call, Put and In the Money definitions",
    `UPDATE academy_lessons l SET content = ${sqlJson({
      pairs: [
        { term: 'Call', definition: 'The right to buy a stock at a set price before a set date.' },
        { term: 'Put', definition: 'The right to sell a stock at a set price before a set date.' },
        { term: 'Strike Price', definition: 'The set price at which you can buy or sell the stock.' },
        { term: 'Premium', definition: 'The upfront cost you pay to buy the option.' },
        { term: 'Expiration', definition: 'The date when the option ends and stops working.' },
        { term: 'In the Money', definition: 'When using the option right now would be worth something, before counting what you paid for it.' },
      ],
    })}\nFROM academy_courses c WHERE c.slug = 'options-basics' AND l.course_id = c.id AND l.type = 'match';`,
  );

  fs.writeFileSync(MIGRATION, sql.join('\n') + '\n');
  fs.writeFileSync(path.join(STAGING, 'sequences.json'), JSON.stringify(sequences, null, 2) + '\n');
  console.error(`Wrote ${MIGRATION} (${checks.length} checks, ${demos.length} demos, ${touched.size} courses).`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
